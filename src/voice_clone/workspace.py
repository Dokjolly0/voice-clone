"""A voice workspace: voices/<name>/, holding every file of one voice and its state.

voices/<name>/
  voice.json            name, language, created; small and stable
  state.json            per-clip progress of the dataset stage (rewritten often, atomically)
  input/                the audio files added with `add-audio`
  reference/            merged.wav (all input), reference.wav (what Drama 3 hears), transcript.txt, voice.gguf
  sentences.txt         the dataset sentences, one per line; line N is clip N
  clips/                clips generated by Drama 3 (kept until verified good)
  dataset/              wav/ at 22050 Hz + metadata.csv, Piper's input
  training/             Piper's cache, lightning_logs/ with checkpoints, train.log
  export/               <locale>-<name>-medium.onnx + .onnx.json
  samples/              test sentences spoken by the exported model
  logs/                 logs and pid of background jobs
"""

import re
import shutil
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from voice_clone import audio, languages
from voice_clone.paths import VOICES_DIR
from voice_clone.util import UserError, info, read_json, write_json

NAME_RE = re.compile(r"^[a-z0-9][a-z0-9_-]{0,39}$")


@dataclass
class Voice:
    name: str
    dir: Path

    # --- paths -------------------------------------------------------------------------------------------------
    @property
    def input_dir(self) -> Path: return self.dir / "input"
    @property
    def reference_dir(self) -> Path: return self.dir / "reference"
    @property
    def sentences_file(self) -> Path: return self.dir / "sentences.txt"
    @property
    def clips_dir(self) -> Path: return self.dir / "clips"
    @property
    def dataset_dir(self) -> Path: return self.dir / "dataset"
    @property
    def training_dir(self) -> Path: return self.dir / "training"
    @property
    def export_dir(self) -> Path: return self.dir / "export"
    @property
    def samples_dir(self) -> Path: return self.dir / "samples"
    @property
    def logs_dir(self) -> Path: return self.dir / "logs"
    @property
    def state_file(self) -> Path: return self.dir / "state.json"

    # --- metadata ----------------------------------------------------------------------------------------------
    @property
    def meta(self) -> dict:
        return read_json(self.dir / "voice.json", {})

    @property
    def language(self) -> languages.Language:
        return languages.get(self.meta["lang"])

    @property
    def model_name(self) -> str:
        return f"{self.language.locale}-{self.name}-medium"

    @property
    def onnx_path(self) -> Path:
        return self.export_dir / f"{self.model_name}.onnx"

    @property
    def onnx_config_path(self) -> Path:
        return self.export_dir / f"{self.model_name}.onnx.json"

    def load_state(self) -> dict:
        return read_json(self.state_file, {})

    def save_state(self, state: dict) -> None:
        write_json(self.state_file, state)

    def inputs(self) -> list[Path]:
        if not self.input_dir.exists():
            return []
        return sorted(p for p in self.input_dir.iterdir() if p.suffix.lower() in audio.AUDIO_EXTENSIONS)

    def sentences(self) -> list[str]:
        if not self.sentences_file.exists():
            return []
        return [l.strip() for l in self.sentences_file.read_text(encoding="utf-8").splitlines() if l.strip()]


def validate_name(name: str) -> str:
    if not NAME_RE.match(name):
        raise UserError("voice names use lowercase letters, digits, '-' and '_' (at most 40, e.g. 'anna' or 'pos-it')")
    return name


def create(name: str, lang: str) -> Voice:
    validate_name(name)
    languages.get(lang)
    vdir = VOICES_DIR / name
    if (vdir / "voice.json").exists():
        raise UserError(f"voice {name!r} already exists in {vdir}")
    vdir.mkdir(parents=True, exist_ok=True)
    write_json(vdir / "voice.json", {"name": name, "lang": lang, "created": datetime.now().isoformat(timespec="seconds")})
    return Voice(name, vdir)


def load(name: str) -> Voice:
    vdir = VOICES_DIR / name
    if not (vdir / "voice.json").exists():
        existing = ", ".join(list_names()) or "none yet"
        raise UserError(f"no voice named {name!r} (existing: {existing}); create it with `voice-clone new {name}`")
    return Voice(name, vdir)


def list_names() -> list[str]:
    if not VOICES_DIR.exists():
        return []
    return sorted(p.name for p in VOICES_DIR.iterdir() if (p / "voice.json").exists())


def _safe_filename(name: str) -> str:
    stem, dot, ext = name.rpartition(".")
    stem = re.sub(r"[^\w.-]+", "_", stem if dot else name).strip("_") or "audio"
    return f"{stem}.{ext.lower()}" if dot else stem


def add_audio(voice: Voice, files: list[Path]) -> list[Path]:
    """Copy audio files into input/, checking each is readable. Returns the new paths."""
    voice.input_dir.mkdir(parents=True, exist_ok=True)
    added = []
    for src in files:
        src = Path(src)
        if not src.is_file():
            raise UserError(f"file not found: {src}")
        if src.suffix.lower() not in audio.AUDIO_EXTENSIONS:
            raise UserError(f"unsupported file type {src.suffix!r}: {src}")
        seconds = audio.duration(src)
        base = voice.input_dir / _safe_filename(src.name)
        dst, n = base, 2
        while dst.exists():
            dst = base.with_name(f"{base.stem}-{n}{base.suffix}")
            n += 1
        shutil.copy2(src, dst)
        added.append(dst)
        info(f"added {dst.name} ({seconds:.1f} s)")
    return added


def remove_audio(voice: Voice, names: list[str]) -> None:
    for name in names:
        path = voice.input_dir / name
        if not path.is_file():
            raise UserError(f"no input file {name!r} in {voice.input_dir}")
        path.unlink()
        info(f"removed {name}")
